const THUMB_EXT: Record<string, string> = {
  'ep02': 'jpg',
  'ep03': 'jpg',
  'ep04': 'jpg',
  'ep28': 'jpeg',
};

function thumb(id: string): string {
  if (!THUMB_EXT[id] && !id.match(/^ep\d+$/)) {
    return '/img/podcast-logo.png';
  }
  const ext = THUMB_EXT[id] ?? 'png';
  return `/img/ep/${id}-thumb.${ext}`;
}

